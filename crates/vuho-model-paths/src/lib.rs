/// Parse and return the embedded manifest, once.
///
/// # Panics
///
/// Panics if `models.manifest.json` fails to parse — an invalid manifest is
/// a build-time/first-use bug, not a recoverable runtime condition (every
/// caller needs a valid manifest to do anything at all, so there is no
/// meaningful fallback).
#[must_use]
pub fn manifest() -> &'static Manifest {
    // The `OnceLock` stores a `Result` so `get_or_init` can never panic
    // (CONSTITUTION rule 17 — a panic inside `get_or_init` poisons it
    // permanently); the panic on a malformed manifest happens out here.
    static MANIFEST: OnceLock<Result<Manifest, serde_json::Error>> = OnceLock::new();
    MANIFEST
        .get_or_init(|| serde_json::from_str(MANIFEST_JSON))
        .as_ref()
        .expect("embedded models.manifest.json must parse")
}

/// Parsed `models.lock.json`: per-file integrity data for the models the
/// manifest names, pinned at the manifest's revision (ADR-020).
#[derive(Debug, serde::Deserialize)]
pub struct Lock {
    /// Lock schema version — bumped whenever the shape below changes.
    pub schema_version: u32,
    /// Each model's locked file set, keyed by the same model id the
    /// manifest uses.
    pub models: BTreeMap<String, SttLock>,
}

impl Lock {
    /// The locked file set for `id`.
    #[must_use]
    pub fn model(&self, id: &str) -> Option<&SttLock> {
        self.models.get(id)
    }
}

/// One model's locked file set: what a complete, untampered download must
/// contain.
#[derive(Debug, serde::Deserialize)]
pub struct SttLock {
    /// Directory name under `user_models_dir()` this lock describes —
    /// mirrors (and must match) `SttModel::dir_name`.
    pub dir_name: String,
    /// Pinned commit revision this lock was generated against — mirrors
    /// (and must match) `SttModel::revision`.
    pub revision: String,
    /// Sum of every locked file's `size`, for progress totals and the
    /// `ModelStatus::Missing { total_bytes }` a resolver miss reports.
    pub total_bytes: u64,
    /// Every locked file, path relative to the model directory.
    pub files: Vec<LockedFile>,
}

/// One locked file: its path (relative to the model directory), exact
/// size, and SHA-256 hash of its content.
#[derive(Debug, serde::Deserialize)]
pub struct LockedFile {
    /// Path relative to the model directory, e.g.
    /// `"ParakeetDecoder.mlmodelc/model.mil"`.
    pub path: String,
    /// Exact expected file size in bytes.
    pub size: u64,
    /// Hex-encoded SHA-256 of the file's content.
    pub sha256: String,
}

/// Parse and return the embedded lock, once.
///
/// Mirrors [`manifest`]'s `OnceLock<Result<...>>` pattern exactly
/// (CONSTITUTION rule 17): the `Result` itself is cached, not just the
/// `Ok` value, so a malformed `models.lock.json` cannot poison the lock
/// into a permanently-unusable state — every call re-observes the same
/// parse failure instead of a generic "already panicked" state.
///
/// # Panics
///
/// Panics if `models.lock.json` fails to parse — an invalid lock is a
/// build-time/first-use bug (it is generated and committed by
/// `scripts/lock-model.sh`, never hand-edited), not a recoverable runtime
/// condition.
#[must_use]
pub fn lock() -> &'static Lock {
    static LOCK: OnceLock<Result<Lock, serde_json::Error>> = OnceLock::new();
    LOCK.get_or_init(|| serde_json::from_str(LOCK_JSON))
        .as_ref()
        .expect("embedded models.lock.json must parse")
}

/// The env-var names and default directory name for one model, extracted
/// from the manifest — the input to [`resolve_model_folder`].
pub struct ModelSpec<'a> {
    /// Env var that overrides the full resolved folder path.
    pub env_folder: &'a str,
    /// Env var that overrides just the directory name.
    pub env_name: &'a str,
    /// Default directory name (under `models/` or `Contents/Resources/`).
    pub default_dir_name: &'a str,
}

/// Why [`resolve_model`] could not name an existing model directory.
#[derive(Debug, Clone)]
pub enum ModelPathError {
    /// The directory name itself is unusable — see [`InvalidDirName`]. No
    /// candidate was built, so nothing was tried.
    InvalidDirName(InvalidDirName),
    /// No candidate location held an existing directory. Carries every
    /// candidate path the resolver actually tried, in the order it tried
    /// them (most to least authoritative — see [`resolve_model_folder`]'s
    /// doc comment), so callers can build an actionable, typed error naming
    /// all of them, not just the last.
    NotFound {
        /// Every candidate path tried, in order.
        tried: Vec<PathBuf>,
    },
}

impl std::fmt::Display for ModelPathError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::InvalidDirName(invalid) => invalid.fmt(f),
            Self::NotFound { tried } => {
                let tried = tried
                    .iter()
                    .map(|p| p.display().to_string())
                    .collect::<Vec<_>>()
                    .join(", ");
                write!(f, "model folder not found — tried: {tried}")
            }
        }
    }
}

impl std::error::Error for ModelPathError {}

impl From<InvalidDirName> for ModelPathError {
    fn from(invalid: InvalidDirName) -> Self {
        Self::InvalidDirName(invalid)
    }
}

/// A model directory name that is not a plain directory name.
///
/// The name is validated where it is produced ([`dir_name_for`]) rather
/// than at the two places it is dangerous, because it is dangerous at both:
/// `vuho-model-fetch` joins it onto [`user_models_dir`] to *download* into,
/// and joins it again to recursively *delete*. `Path::starts_with` compares
/// whole components, so `..` is simply another component and
/// `<user_dir>/../../../../tmp/victim` starts with `<user_dir>` by that
/// test while the OS resolves the `..` at open time onto an unrelated
/// directory. One `Component::Normal` and nothing else is the property that
/// makes the join mean what the guard reads it as.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct InvalidDirName {
    /// Where the rejected value came from: the env var that set it, or
    /// [`MANIFEST_ORIGIN`] when the manifest's own `dir_name` is at fault.
    pub origin: String,
    /// The rejected value, verbatim.
    pub value: String,
}

impl std::fmt::Display for InvalidDirName {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(
            f,
            "model directory name {:?} (from {}) is not a single plain directory name — no separators, no `.` or `..`, no drive or root",
            self.value, self.origin
        )
    }
}

impl std::error::Error for InvalidDirName {}

/// [`InvalidDirName::origin`] for a name that came from the embedded
/// manifest rather than from an env var.
pub const MANIFEST_ORIGIN: &str = "models.manifest.json";

/// `name` if it is exactly one [`Component::Normal`] and nothing else.
fn plain_dir_name(name: String, origin: &str) -> Result<String, InvalidDirName> {
    let mut components = Path::new(&name).components();
    match (components.next(), components.next()) {
        (Some(Component::Normal(only)), None) if only == OsStr::new(&name) => Ok(name),
        _ => Err(InvalidDirName {
            origin: origin.to_owned(),
            value: name,
        }),
    }
}

fn non_empty_env(key: &str) -> Option<String> {
    std::env::var(key).ok().filter(|s| !s.is_empty())
}

/// `Contents/Resources` of the innermost `.app` bundle enclosing `exe`, or
/// `None` if no ancestor directory is actually an app bundle.
///
/// Walks `exe`'s ancestors from most to least specific (`Path::ancestors`)
/// rather than string-searching for the literal substring `".app/Contents"`
/// in the path — the string search had two failure modes this walk fixes:
/// a *nested* bundle (e.g. a plug-in's `.app` inside a host app's
/// `Contents/PlugIns/`) would match the outermost `.app` first (the
/// leftmost occurrence), not the one actually enclosing `exe`; and a
/// coincidentally-named sibling directory like `Contents-backup` shares
/// `".app/Contents"` as a literal prefix of its own name, so the string
/// search would silently match it too. This walk instead requires the
/// ancestor itself to have the `.app` extension AND to contain a real
/// `Contents` directory (checked by name, not by prefix) before accepting
/// it.
fn resources_dir_for_exe(exe: &Path) -> Option<PathBuf> {
    exe.ancestors()
        .find(|dir| {
            dir.extension().is_some_and(|ext| ext == "app") && dir.join("Contents").is_dir()
        })
        .map(|app_dir| app_dir.join("Contents").join("Resources"))
}

/// `Contents/Resources` of the enclosing `.app`, if the running executable
/// is inside one. A bare `cargo run` binary (`target/debug/vuho`) has no
/// `.app` ancestor, so this is `None` there.
fn bundle_resources_dir() -> Option<PathBuf> {
    let exe = std::env::current_exe().ok()?;
    resources_dir_for_exe(&exe)
}

/// Workspace-relative `models/` directory, used by `cargo run` and `cargo
/// test`.
///
/// `CARGO_MANIFEST_DIR` is baked in at compile time
/// (`…/crates/vuho-model-paths`), so this is absolute and independent of the
/// current working directory. Any crate directly under `crates/` resolves
/// to the same workspace root this way, so centralizing the computation
/// here — rather than duplicating it per caller crate — is correct, not
/// incidental.
fn dev_models_dir() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent() // crates/
        .and_then(Path::parent) // workspace root
        .expect("CARGO_MANIFEST_DIR should be two levels below the workspace root")
        .join("models")
}

/// The single definition of where Vuho downloads the model to (ADR-020):
/// `$HOME/Library/Application Support/Vuho/models`. The resolver's
/// lowest-priority candidate, and the one directory a downloader
/// (`vuho-model-fetch`) is ever allowed to write into.
///
/// `$HOME` is read directly via `std::env::var`, not the `dirs` crate:
/// this crate is deliberately std-only (ADR-019), and its only callers are
/// macOS-only, so hardcoding the macOS `Library/Application Support` layout
/// here is the correct scope, not a shortcut that happens to work.
///
/// Returns `None` — never a fabricated relative path, never a panic —
/// when `$HOME` is unset or empty. A caller that gets `None` here simply
/// doesn't have this candidate to try; [`resolve_model_folder`] treats it
/// exactly like a bundle candidate absent because the process isn't inside
/// an `.app`.
#[must_use]
pub fn user_models_dir() -> Option<PathBuf> {
    non_empty_env("HOME").map(|home| {
        Path::new(&home)
            .join("Library")
            .join("Application Support")
            .join("Vuho")
            .join("models")
    })
}

/// The directory name to resolve for `spec`: `spec.env_name`'s override, or
/// `spec.default_dir_name`.
///
/// Public so every caller that needs to name the model directory —
/// [`resolve_model_folder`]'s own candidate-building below, and
/// `vuho-model-fetch`'s downloader/availability check — agrees on the same
/// override, instead of `vuho-model-fetch` reading `Lock::stt.dir_name`
/// directly and silently ignoring an operator's `VUHO_MODEL_NAME` override
/// that `resolve_model_folder` already honors.
///
/// `spec.env_name` is manifest-wide: one value renames the directory of
/// **every** model, not just the selected one. See [`SttManifest::spec_for`]
/// for why that is deliberate.
///
/// # Errors
///
/// Returns [`InvalidDirName`] when the name is anything but a single plain
/// directory name — which is a hard refusal, never a fall back to the
/// manifest default, because a caller that quietly got the default would
/// then download into (or delete) a directory the operator did not ask for.
pub fn dir_name_for(spec: &ModelSpec<'_>) -> Result<String, InvalidDirName> {
    match non_empty_env(spec.env_name) {
        Some(override_name) => plain_dir_name(override_name, spec.env_name),
        None => plain_dir_name(spec.default_dir_name.to_owned(), MANIFEST_ORIGIN),
    }
}

/// Every candidate model-directory location for `spec`, most to least
/// authoritative — see [`resolve_model_folder`]'s doc comment for the
/// order and rationale. A candidate is included only when its source is
/// actually available (e.g. no bundle entry when not running inside an
/// `.app`, no user-dir entry when `$HOME` is unset) — the returned list is
/// exactly what gets tried, and exactly what [`ModelPathError::tried`]
/// reports on failure.
fn candidate_paths(spec: &ModelSpec<'_>) -> Result<Vec<Resolved>, InvalidDirName> {
    let dir_name = dir_name_for(spec)?;

    // The full-path override is terminal, not merely first: if the operator
    // named a folder, that folder is the answer or there is no answer.
    // Falling through to the bundle/dev/user candidates would mean a typo in
    // `VUHO_MODEL_FOLDER` silently loads a *different* model than the one
    // asked for, and reports success — the operator has no way to tell their
    // override was ignored. An error naming the path they actually typed is
    // the only honest outcome. (This is the pre-ADR-020 behavior, preserved
    // deliberately: the old `map_or_else` took its else-branch only when the
    // variable was unset.)
    if let Some(folder) = non_empty_env(spec.env_folder) {
        return Ok(vec![Resolved {
            path: PathBuf::from(folder),
            source: ModelSource::EnvOverride,
        }]);
    }

    let mut candidates = Vec::with_capacity(3);
    if let Some(resources) = bundle_resources_dir() {
        candidates.push(Resolved {
            path: resources.join(&dir_name),
            source: ModelSource::Bundle,
        });
    }
    candidates.push(Resolved {
        path: dev_models_dir().join(&dir_name),
        source: ModelSource::DevTree,
    });
    if let Some(user_dir) = user_models_dir() {
        candidates.push(Resolved {
            path: user_dir.join(&dir_name),
            source: ModelSource::UserData,
        });
    }

    Ok(candidates)
}

/// Which of [`resolve_model`]'s candidate locations a model directory came
/// from. Load-bearing beyond diagnostics: ADR-020 lets Vuho verify — and
/// delete — only the tree it downloaded itself, i.e. only
/// [`ModelSource::UserData`].
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum ModelSource {
    /// The `env_folder` full-path override.
    EnvOverride,
    /// The enclosing `.app`'s `Contents/Resources/<name>`.
    Bundle,
    /// The workspace-relative `models/<name>` dev directory.
    DevTree,
    /// `<name>` under [`user_models_dir`] — the one tree a downloader
    /// writes into.
    UserData,
}

/// A resolved model directory and the candidate location it came from.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Resolved {
    /// The existing directory holding the model.
    pub path: PathBuf,
    /// Which candidate produced [`Self::path`].
    pub source: ModelSource,
}

/// Resolve a model directory — the single chokepoint any caller learns
/// where a model lives, shared by `vuho-stt-engine::resolve_model_folder`
/// and (via `availability()`) `vuho-model-fetch`.
///
/// Tries, in order, the first candidate that is an existing directory:
///
/// 1. `spec.env_folder` (full path override, e.g. `VUHO_MODEL_FOLDER`).
/// 2. The enclosing `.app`'s `Contents/Resources/<name>` — keeps a DMG
///    build offline from first launch.
/// 3. The workspace-relative `models/<name>` dev directory — `cargo run` /
///    `cargo test`; never exists for an end user.
/// 4. `<name>` under [`user_models_dir`] (ADR-020) — the one tree a
///    downloader ever writes into.
///
/// `<name>` is `spec.env_name`'s override, or `spec.default_dir_name`, and
/// must be a single plain directory name either way ([`dir_name_for`]).
///
/// Both env vars are manifest-wide, so candidate 1 in particular answers
/// for **every** model id, not only the one it was set for — see
/// [`SttManifest::spec_for`].
///
/// The order is deliberate, not incidental: candidate 3 before candidate 4
/// preserves `cargo run` / `cargo test` / `test-stt-ffi` behavior exactly
/// as it was before ADR-020 added the user-data candidate — a developer's
/// workspace `models/` checkout always wins over a stale download sitting
/// in `~/Library/Application Support/Vuho/models`.
///
/// Vuho's own resolver never downloads a model — a directory that isn't on
/// disk at any candidate is an error here rather than a silent network
/// fetch; only `vuho-model-fetch`, gated behind an explicit user action,
/// ever performs network I/O (ADR-020).
///
/// # Errors
///
/// Returns [`ModelPathError::InvalidDirName`] for an unusable directory
/// name, or [`ModelPathError::NotFound`] naming every candidate tried if
/// none of them is an existing directory.
pub fn resolve_model_folder(spec: &ModelSpec<'_>) -> Result<PathBuf, ModelPathError> {
    resolve_model(spec).map(|resolved| resolved.path)
}

/// [`resolve_model_folder`], plus which candidate location answered — the
/// distinction ADR-020's "Vuho owns only bytes it fetched" invariant is
/// built on.
///
/// # Errors
///
/// Returns [`ModelPathError::InvalidDirName`] when the directory name (or
/// its `env_name` override) is not a single plain directory name, and
/// [`ModelPathError::NotFound`] naming every candidate tried if none of
/// them is an existing directory.
pub fn resolve_model(spec: &ModelSpec<'_>) -> Result<Resolved, ModelPathError> {
    let candidates = candidate_paths(spec)?;
    match candidates.iter().find(|candidate| candidate.path.is_dir()) {
        Some(found) => Ok(found.clone()),
        None => Err(ModelPathError::NotFound {
            tried: candidates.into_iter().map(|c| c.path).collect(),
        }),
    }
}

/// Process-local counter for [`unique_temp_path`], so two racing callers in
/// the same process never pick the same temp-file name before either
/// `rename` lands.
static TEMP_SEQ: AtomicU64 = AtomicU64::new(0);

/// Build a unique temp-file path alongside `path`, in the same directory
/// (so [`atomic_write`]'s `rename` is a same-filesystem atomic move).
///
/// Uniqueness comes from the process ID plus a process-local monotonic
/// counter — not a timestamp, which two calls within the same clock tick
/// (the common case for a tight retry loop or two racing threads) could
/// collide on.
fn unique_temp_path(path: &Path) -> PathBuf {
    let seq = TEMP_SEQ.fetch_add(1, Ordering::Relaxed);
    let mut name = path
        .file_name()
        .map_or_else(|| "vuho".to_string(), |n| n.to_string_lossy().into_owned());
    let _ = write!(name, ".tmp.{}.{seq}", std::process::id());
    path.with_file_name(name)
}

/// Atomically replace the file at `path` with `bytes`.
///
/// Durability chain: write `bytes` to a unique temp file in `path`'s
/// parent directory → `File::sync_all` the temp file (flush its content to
/// durable storage before it's ever visible under the real name) →
/// `fs::rename` (atomic same-filesystem move) → best-effort fsync of the
/// parent directory (makes the rename's directory-entry update durable
/// too — without this, a crash immediately after rename can, on some
/// filesystems, leave the directory entry still pointing at the old inode
/// after an unclean shutdown, even though the rename "completed").
///
/// Callers are responsible for creating `path`'s parent directory first —
/// this function does not create directories, since its two current
/// callers (`vuho-settings`, and the model downloader's sidecar manifest)
/// already have their own directory-creation step with their own error
/// handling.
///
/// Std-only, per ADR-019's "deliberately std-only" scope for this crate:
/// no `tempfile` crate, just `std::fs`/`std::io`.
///
/// # Errors
///
/// Returns the underlying [`std::io::Error`] if the temp file can't be
/// created, written, or `sync_all`'d, or if the rename fails. A failed
/// parent-directory fsync is logged nowhere by this function (it has no
/// logging dependency) and does not fail the call — see the durability
/// chain above.
pub fn atomic_write(path: &Path, bytes: &[u8]) -> std::io::Result<()> {
    let tmp_path = unique_temp_path(path);
    {
        let mut file = std::fs::File::create(&tmp_path)?;
        file.write_all(bytes)?;
        file.sync_all()?;
    }
    std::fs::rename(&tmp_path, path)?;

    if let Some(parent) = path.parent() {
        // Best-effort: directory fsync isn't universally meaningful (some
        // filesystems/sandboxes don't support it), and losing the last few
        // milliseconds of directory-entry durability on an otherwise-
        // successful write is not worth turning this into a hard failure.
        let _ = std::fs::File::open(parent).and_then(|dir| dir.sync_all());
    }
    Ok(())
}

