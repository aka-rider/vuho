    /// A unique temp directory, removed on drop, for building fake
    /// candidate model directories in tests without touching the real
    /// workspace `models/` or `$HOME`.
    struct TempDir(PathBuf);

    impl TempDir {
        fn new(label: &str) -> Self {
            static SEQ: AtomicU64 = AtomicU64::new(0);
            let seq = SEQ.fetch_add(1, Ordering::Relaxed);
            let dir = std::env::temp_dir().join(format!(
                "vuho-model-paths-test-{label}-{}-{seq}",
                std::process::id()
            ));
            let _ = std::fs::remove_dir_all(&dir);
            std::fs::create_dir_all(&dir).expect("create temp dir");
            Self(dir)
        }
    }

    impl Drop for TempDir {
        fn drop(&mut self) {
            let _ = std::fs::remove_dir_all(&self.0);
        }
    }

    /// RAII guard around a real subdirectory of `dev_models_dir()` — used
    /// only by the handful of tests below that must exercise the *actual*
    /// dev-dir candidate `resolve_model_folder` walks (a fixed,
    /// compile-time path derived from `CARGO_MANIFEST_DIR`, so it cannot be
    /// swapped for a fake temp dir the way the other candidates can).
    ///
    /// `dev_models_dir()` resolves to the real workspace `models/` — the
    /// same tree `./scripts/fetch-model.sh` provisions ~496 MB of real
    /// model weights into on a developer's machine. `name` must already be
    /// a test-unique string (every caller below passes one derived from its
    /// own test name), and this guard's `Drop` removes exactly that
    /// directory — unlike a bare `create_dir_all`/`remove_dir_all` pair, a
    /// panic mid-test still runs the destructor and leaves nothing behind
    /// in a directory a previous incident (a symlink committed into this
    /// same tree, destroying the real 496 MB checkout on merge) has already
    /// shown is unsafe to touch carelessly.
    struct RealDevDirGuard(PathBuf);

    impl RealDevDirGuard {
        fn create(name: &str) -> Self {
            let dir = dev_models_dir().join(name);
            let _ = std::fs::remove_dir_all(&dir);
            std::fs::create_dir_all(&dir).expect("create real dev-dir candidate");
            Self(dir)
        }
    }

    impl Drop for RealDevDirGuard {
        fn drop(&mut self) {
            let _ = std::fs::remove_dir_all(&self.0);
        }
    }

    /// RAII guard that sets an env var for the test and restores its prior
    /// value on drop — keeps env-mutating tests from leaking state into
    /// whichever test runs next in the same process.
    struct EnvGuard {
        key: &'static str,
        prev: Option<String>,
    }

    impl EnvGuard {
        fn set(key: &'static str, value: &str) -> Self {
            let prev = std::env::var(key).ok();
            // SAFETY: tests in this module run single-threaded with
            // respect to each other's use of these specific keys (each
            // uses a `VUHO_MODEL_PATHS_TEST_*`-prefixed or `HOME` key
            // guarded by this same RAII type, restored before the next
            // test can observe it).
            unsafe { std::env::set_var(key, value) };
            Self { key, prev }
        }
    }

    impl Drop for EnvGuard {
        fn drop(&mut self) {
            match &self.prev {
                Some(v) => unsafe { std::env::set_var(self.key, v) },
                None => unsafe { std::env::remove_var(self.key) },
            }
        }
    }

